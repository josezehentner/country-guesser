// Builds data/borders.js, the land borders between the quizzed countries, from
// data/world.json. Regenerate with `npm run build:borders`.
//
// mapshaper simplified the map with its topology intact, so neighbors share the
// points of their common border exactly. Entries under 100 km² kept full detail and
// were enlarged instead, so their borders are listed by hand below.
import { readFileSync, writeFileSync } from 'node:fs';
import { COUNTRY_BY_CODE } from '../data/countries.js';

// Real land borders the data cannot show, because one side was enlarged.
const ADDED = [
  ['IT', 'SM'],
  ['IT', 'VA'],
  ['FR', 'MC'],
  ['ES', 'GI'],
  ['CN', 'MO'],
  ['MF', 'SX'],
];
// Pairs that only meet in a single point of the data without a border on the ground:
// Namibia and Zimbabwe come close at the Zambezi but do not touch. Botswana and
// Zambia do share a few hundred meters at Kazungula, so they stay.
const REMOVED = [['NA', 'ZW']];

const world = JSON.parse(readFileSync(new URL('../data/world.json', import.meta.url)));
const key = ([lon, lat]) => `${lon.toFixed(5)},${lat.toFixed(5)}`;
const ownersByPoint = new Map();
for (const feature of world.features) {
  const code = feature.properties.id;
  // Disputed or unclaimed areas such as Kashmir or Bir Tawil are not quizzed; the
  // countries around them border each other directly as well.
  if (!COUNTRY_BY_CODE.has(code)) continue;
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  for (const ring of polygons.flat()) {
    for (const point of ring) {
      const owners = ownersByPoint.get(key(point)) ?? new Set();
      owners.add(code);
      ownersByPoint.set(key(point), owners);
    }
  }
}

const neighbors = new Map();
const link = (a, b) => {
  if (!neighbors.has(a)) neighbors.set(a, new Set());
  if (!neighbors.has(b)) neighbors.set(b, new Set());
  neighbors.get(a).add(b);
  neighbors.get(b).add(a);
};
for (const owners of ownersByPoint.values()) {
  const codes = [...owners];
  for (let i = 0; i < codes.length; i++) for (let j = i + 1; j < codes.length; j++) link(codes[i], codes[j]);
}
for (const [a, b] of ADDED) link(a, b);
for (const [a, b] of REMOVED) {
  neighbors.get(a).delete(b);
  neighbors.get(b).delete(a);
}

const lines = [...neighbors.keys()].sort().map((code) => `  ${code}: '${[...neighbors.get(code)].sort().join(' ')}',`);
const source = [
  '// Land borders between the quizzed countries, generated by tools/borders.js from',
  '// data/world.json. Do not edit by hand: change the lists in that script and run',
  '// `npm run build:borders`. Bridges and tunnels are no land border.',
  'const NEIGHBORS = {',
  ...lines,
  '};',
  '',
  'export const BORDERS = Object.fromEntries(Object.entries(NEIGHBORS).map(([code, list]) => [code, list.split(\' \')]));',
  '',
].join('\n');
writeFileSync(new URL('../data/borders.js', import.meta.url), source);
console.log(`${neighbors.size} countries with land borders`);
